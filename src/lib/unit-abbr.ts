  환경보건연구실: '보건실',
  환경사회연구실: '사회실',
  탄소중립에너지연구실: '탄중실',
  녹색경제연구실: '녹색실',
  대기환경연구실: '대기실',
  기후적응정책실: '정책실',
  기후적응협력실: '협력실',
  국토전략평가실: '국토',
  사회기반평가실: '기반',
